using AMAIS.WKFLO.Common.Models.Config;
using AMAIS.WKFLO.Common.Models.Results;
using AMAIS.WKFLO.MD.Application.Common;
using AMAIS.WKFLO.MD.Application.Tools.Commands.InstallMarketplaceTool;
using AMAIS.WKFLO.MD.Application.Tools.Models;
using Newtonsoft.Json;
using System.Threading;
using System.Threading.Tasks;

namespace AMAIS.WKFLO.MD.UnitTests.Application.Tools.Commands.InstallMarketplaceTool
{
    public class InstallMarketplaceToolCommandHandlerTests : IClassFixture<InstallMarketplaceToolCommandHandlerTesting>
    {
        private readonly InstallMarketplaceToolCommandHandlerTesting _testing;

        public InstallMarketplaceToolCommandHandlerTests(InstallMarketplaceToolCommandHandlerTesting testing)
        {
            _testing = testing;
        }

        [Fact]
        public async Task Handle_WithValidMarketplaceTool_ShouldReturnSuccessResult()
        {
            // Arrange
            var command = new InstallMarketplaceToolCommand
            {
                Id = _testing.MarketplaceToolId
            };

            // Act
            var result = await _testing.InstallMarketplaceToolCommandHandler.Handle(command, CancellationToken.None);

            // Assert
            Assert.IsType<SuccessResult<TenantToolCreateResult>>(result);
            var successResult = ((SuccessResult<TenantToolCreateResult>)result).Data;
            Assert.NotNull(successResult);
            Assert.Equal("Test Tool", successResult.Name);
            Assert.Equal("Test Tool Description", successResult.Description);
            Assert.Equal("API", successResult.Type);
            Assert.Equal("{\"endpoint\": \"https://api.example.com\"}", successResult.Config);
            Assert.True(successResult.IsActive);
        }

        [Fact]
        public async Task Handle_WithNonExistentMarketplaceTool_ShouldReturnNotFoundResult()
        {
            // Arrange
            var command = new InstallMarketplaceToolCommand
            {
                Id = 999 // Non-existent ID
            };

            // Act
            var result = await _testing.InstallMarketplaceToolCommandHandler.Handle(command, CancellationToken.None);

            // Assert
            Assert.IsType<NotFoundResult>(result);
            var notFoundResult = (NotFoundResult)result;
            Assert.Contains(notFoundResult.Errors, e => e.Code == ErrorConst.ToolNotFound);
        }

        [Fact]
        public async Task Handle_WithValidCommand_ShouldCreateTenantToolWithCorrectProperties()
        {
            // Arrange
            var command = new InstallMarketplaceToolCommand
            {
                Id = _testing.MarketplaceToolId
            };

            // Act
            var result = await _testing.InstallMarketplaceToolCommandHandler.Handle(command, CancellationToken.None);

            // Assert
            Assert.IsType<SuccessResult<TenantToolCreateResult>>(result);
            var successResult = ((SuccessResult<TenantToolCreateResult>)result).Data;

            // Verify that the TenantTool was created with correct default values
            Assert.True(successResult.IsActive); // Should be active by default when installing
            Assert.Equal(0, successResult.Id); // Should be 0 initially (will be generated by EF)
        }

        [Theory]
        [InlineData(0)]
        [InlineData(-1)]
        [InlineData(-100)]
        public async Task Handle_WithInvalidId_ShouldReturnNotFoundResult(int invalidId)
        {
            // Arrange
            var command = new InstallMarketplaceToolCommand
            {
                Id = invalidId
            };

            // Act
            var result = await _testing.InstallMarketplaceToolCommandHandler.Handle(command, CancellationToken.None);

            // Assert
            Assert.IsType<NotFoundResult>(result);
        }

        [Fact]
        public async Task Handle_WithOAuth2McpTool_StripsClientCredentialsAndRedirectUri_KeepsDescriptiveFields()
        {
            // Arrange
            var command = new InstallMarketplaceToolCommand
            {
                Id = _testing.OAuthMarketplaceToolId
            };

            // Act
            var result = await _testing.InstallMarketplaceToolCommandHandler.Handle(command, CancellationToken.None);

            // Assert
            Assert.IsType<SuccessResult<TenantToolCreateResult>>(result);
            var installed = ((SuccessResult<TenantToolCreateResult>)result).Data;

            var config = JsonConvert.DeserializeObject<McpServerConfig>(installed.Config);
            Assert.Equal(string.Empty, config.ClientId);
            Assert.Equal(string.Empty, config.ClientSecret);
            Assert.Equal(string.Empty, config.RedirectUri);

            // Descriptive fields (not secrets) must survive the copy untouched.
            Assert.Equal(McpAuthType.OAuth2, config.AuthType);
            Assert.Equal("https://mcp.humantic.ai/mcp", config.Endpoint);
            Assert.Equal(TransportType.Http, config.TransportType);
            Assert.Single(config.Scopes, "profiles:read");
        }

        [Fact]
        public async Task Handle_WithNonOAuthMcpToolCarryingCredentials_StillStripsThem()
        {
            var result = await _testing.InstallMarketplaceToolCommandHandler.Handle(
                new InstallMarketplaceToolCommand { Id = _testing.NonOAuthMcpWithCredentialsMarketplaceToolId }, CancellationToken.None);

            var installed = Assert.IsType<SuccessResult<TenantToolCreateResult>>(result).Data;
            Assert.DoesNotContain("stray-client", installed.Config);
            Assert.DoesNotContain("stray-secret", installed.Config);
        }

        [Fact]
        public async Task Handle_WithNonOAuthMcpToolWithoutCredentials_DoesNotTouchConfig()
        {
            var result = await _testing.InstallMarketplaceToolCommandHandler.Handle(
                new InstallMarketplaceToolCommand { Id = _testing.NonOAuthMcpMarketplaceToolId }, CancellationToken.None);

            var installed = Assert.IsType<SuccessResult<TenantToolCreateResult>>(result).Data;
            Assert.Equal(InstallMarketplaceToolCommandHandlerTesting.NonOAuthMcpConfig, installed.Config);
        }

        [Fact]
        public async Task Handle_WithNonOAuthTool_DoesNotTouchConfig()
        {
            // Arrange
            var command = new InstallMarketplaceToolCommand
            {
                Id = _testing.MarketplaceToolId
            };

            // Act
            var result = await _testing.InstallMarketplaceToolCommandHandler.Handle(command, CancellationToken.None);

            // Assert
            Assert.IsType<SuccessResult<TenantToolCreateResult>>(result);
            var installed = ((SuccessResult<TenantToolCreateResult>)result).Data;
            Assert.Equal("{\"endpoint\": \"https://api.example.com\"}", installed.Config);
        }

        [Fact]
        public async Task Handle_WithDeletedMarketplaceTool_ShouldReturnNotFoundResult()
        {
            // Arrange
            var command = new InstallMarketplaceToolCommand
            {
                Id = _testing.MarketplaceToolId
            };

            // Note: This test would require modifying the testing setup to include a deleted tool
            // For now, we test with a non-existent ID which simulates the same behavior

            // Act
            var result = await _testing.InstallMarketplaceToolCommandHandler.Handle(new InstallMarketplaceToolCommand { Id = 888 }, CancellationToken.None);

            // Assert
            Assert.IsType<NotFoundResult>(result);
        }
    }
}